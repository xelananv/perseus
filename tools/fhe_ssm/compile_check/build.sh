#!/bin/bash
# build.sh — build tools/fhe_ssm/compile_check (main.rs) against this worktree's pc-program, CPU only (no CUDA).
#   bash tools/fhe_ssm/compile_check/build.sh            -> prints the binary's path
# The Cargo project is generated OUTSIDE the tracked tree, in BUILD_DIR (default <worktree>/.cache/fhe_ssm/compile_check,
# gitignored), with path dependencies on <worktree>/crates/{pc-program,pc-config,pc-shadow} (pc-program's default
# features: the CUDA-free compiler) and the worktree's Cargo.lock, so the build tracks upstream and leaves nothing in git.
# Toolchain: RUSTUP_TOOLCHAIN (default stable). The build runs with BUILD_DIR as its working directory; a cargo or
# rustup command run INSIDE the worktree reads its rust-toolchain.toml (channel 1.99.1) and rustup installs that channel
# over the network if it is missing. Under <worktree>/../../tools/memguard.sh 4 when that script exists.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
W=$(git -C "$HERE" rev-parse --show-toplevel)
B=${BUILD_DIR:-$W/.cache/fhe_ssm/compile_check}
mkdir -p "$B/src"
cp "$HERE/main.rs" "$B/src/main.rs"
sed -n '/^\[workspace.dependencies\]/,/^\[/p' "$W/Cargo.toml" | grep -E '^(serde_json|serde|thiserror) *=' >/dev/null \
    || { echo "build.sh: $W/Cargo.toml has no [workspace.dependencies] serde_json" >&2; exit 2; }
SJ=$(sed -n '/^\[workspace.dependencies\]/,/^\[/p' "$W/Cargo.toml" | grep -E '^serde_json *=' | sed 's/^serde_json *= *//')
cat > "$B/Cargo.toml" <<TOML
# generated by tools/fhe_ssm/compile_check/build.sh from $W ($(git -C "$W" rev-parse --short HEAD))
[package]
name = "fhe-ssm-compile-check"
version = "0.1.0"
edition = "2021"
publish = false

[[bin]]
name = "compile_check"
path = "src/main.rs"

[dependencies]
pc-program = { path = "$W/crates/pc-program" }
serde_json = $SJ

[workspace]

[profile.release]
opt-level = 3
TOML
cp "$W/Cargo.lock" "$B/Cargo.lock"
GUARD=()
MG="$W/../../tools/memguard.sh"
[ -x "$MG" ] && GUARD=("$MG" 4)
( cd "$B" && RUSTUP_TOOLCHAIN=${RUSTUP_TOOLCHAIN:-stable} ${GUARD[@]+"${GUARD[@]}"} cargo build --release -q 2>&1 | tail -20 )
BIN="$B/target/release/compile_check"
[ -x "$BIN" ] || { echo "build.sh: no binary at $BIN" >&2; exit 1; }
echo "$BIN"
